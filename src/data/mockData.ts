export function getCreatorByHandle(handle: string): Creator {
  const reel = reels.find((r) => r.handle === handle);
  const base = reel ?? reels[0];
  if (handle === 'john') {
    return {
      id: base.id,
      username: 'John',
      handle: 'john',
      avatar: johnAvatar,
      followers: 0,
      following: 0,
      syncPoints: currentUser.totalSyncPoints,
      bio: 'Test bot account · posts are for testing.',
      verified: false,
      hasBlueprintBadge: false,
      hasHypeMagnatBadge: false,
      posts: johnPosts.map(({ id, image, gradient, likes }) => ({
        id,
        contentId: `john-post-${id}`,
        image,
        gradient,
        likes,
      })),
      reels: reels
        .filter((item) => item.handle === 'john')
        .map((item, index) => ({
          id: item.id,
          contentId: item.contentId,
          image: P([2182970, 1493111][index]),
          gradient: item.gradient,
          likes: item.likes,
        })),
    };
  }
  const seed = base.id * 7;
  const posts = Array.from({ length: 9 }).map((_, i) => {
    const gradients = [
      'from-green-400 to-teal-600',
      'from-purple-400 to-pink-600',
      'from-orange-400 to-rose-600',
      'from-cyan-400 to-indigo-600',
      'from-rose-400 to-red-600',
      'from-emerald-400 to-green-600',
      'from-fuchsia-400 to-purple-600',
      'from-amber-400 to-orange-600',
      'from-sky-400 to-blue-600',
    ];
    const imageIds = [257904, 3764011, 1571939, 164938, 256541, 546819, 1640777, 1552242, 1762851];
    return {
      id: seed + i,
      gradient: gradients[(seed + i) % gradients.length],
      image: P(imageIds[(seed + i) % imageIds.length]),
      likes: ((seed * (i + 3)) % 5000) + 200,
    };
  });
  return {
    id: base.id,
    username: base.username,
    handle: base.handle,
    avatar: base.avatar,
    followers: base.likes,
    following: 150 + (base.id * 40),
    syncPoints: Math.max(0, base.inFeeds * 10),
    bio: base.hasBlueprintBadge
      ? 'Building things, sharing the journey'
      : base.hasHypeMagnatBadge
        ? 'Hype is a lifestyle'
        : 'just here for the vibes',
    verified: base.verified,
    hasBlueprintBadge: base.hasBlueprintBadge,
    hasHypeMagnatBadge: base.hasHypeMagnatBadge,
    posts,
  };
}

export function formatCount(n: number): string {
  if (n >= 1000000) return (n / 1000000).toFixed(1) + 'M';
  if (n >= 1000) return (n / 1000).toFixed(1) + 'K';
  return n.toString();
}
